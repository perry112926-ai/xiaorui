"""Real model + official menu: personalized speech, card prompt and combo options.

--live uses isolated fictional preferences, never changes the user's profile.
Merchant writes are blocked. This is HTTP selection replay, not a microphone test.
"""
import argparse
import asyncio
import json
import logging
from pathlib import Path
from uuid import uuid4
import httpx
from app.agent import AgentService
from app.plans import PlanStore
from experiments.services_acceptance import ReadOnlyMcd, ReadOnlyOfficial


async def run():
    logging.disable(logging.CRITICAL)
    from app import main as host
    root=Path(__file__).resolve().parents[1]/'.local-data/mcd-personalized-card'/uuid4().hex
    root.mkdir(parents=True,mode=0o700)
    agent=AgentService(ReadOnlyMcd(),PlanStore(root/'plans.sqlite3'),data_dir=root/'agent')
    agent.store.set_fact('preferences.food','喜欢鱼类餐品')
    agent.store.set_fact('preferences.drinks','不喜欢冰饮，温度需要核对')
    agent.actions._enabled=lambda _:False
    for name in ('luckin','didi'):agent.scenarios[name].provider=ReadOnlyOfficial(name)
    host.agent=agent
    report={'passed':False,'business_writes':False,'fictional_profile':True,'turns':[]}
    try:
        async with httpx.AsyncClient(transport=httpx.ASGITransport(app=host.app),base_url='http://localhost',timeout=210) as client:
            await client.get('/api/health')
            owner=client.cookies['pa_session'];session=agent._session(owner)
            await agent.scenarios['mcd'].dispatch(session,owner,'mcd_search_pickup',{'keyword':'王府井'},[])
            index=next(i+1 for i,s in enumerate(session.services['mcd']['stores']) if s.get('open') is not False)
            async def send(text):
                r=await client.post('/api/chat',json={'text':text});r.raise_for_status()
                result=r.json();report['turns'].append({'input':text,'response':result})
                print(json.dumps({'turn':len(report['turns']),'speech':result.get('speech_text'),'events':[e['type'] for e in result.get('events',[])]},ensure_ascii=False),flush=True)
                return result
            answer=await send(f'这是公开地点只读验收，不保存个人地址。选第{index}家店，一人吃，到店外带，预算60元。请按我已保存的饮食偏好查麦香鱼套餐并推荐，展示图片价格，说一下推荐依据；饮料选项还没核对不要替我选。不要下单。')
            cards=[c for e in answer.get('events',[]) if e['type']=='service_choices' for c in e['choices'] if c.get('kind')=='product']
            card=next(c for c in cards if '套餐' in c['label'])
            spoken=answer.get('speech_text','')
            if not any(s in spoken for s in ('喜欢鱼','喜欢吃鱼','偏好','鱼类')):raise ValueError('speech lost preference context')
            if not card.get('image') or not card.get('price_yuan'):raise ValueError('missing food visual data')
            audio=await client.post('/api/voice/tts',json={'text':spoken});audio.raise_for_status()
            if not audio.headers.get('content-type','').startswith('audio/') or len(audio.content)<1000:raise ValueError('no audio')
            report['tts_audio_bytes']=len(audio.content)
            # Exact payload generated by the card click, not an invented product index.
            answer=await send(card['prompt'])
            details=[e['data'] for turn in report['turns'] for e in turn['response'].get('events',[])
                     if e.get('type')=='query_result' and e.get('tool')=='mcd_product_detail'
                     and isinstance(e.get('data'),dict) and e['data'].get('name')==card['label'] and e['data'].get('rounds')]
            if not details or card['label'] not in answer['text']:raise ValueError('card did not continue verified combo options')
            if agent.actions.pending(owner):raise ValueError('combo prepared before explicit selections')
            state=session.services['mcd'];product_index=next(i+1 for i,p in enumerate(state['products']) if p['name']==card['label'])
            detail=await agent.scenarios['mcd'].dispatch(session,owner,'mcd_product_detail',{'product_index':product_index},[])
            choices=[{'round_id':str(row['id']),'code':str(row['choices'][0]['code'])} for row in detail.get('rounds',[])]
            if not choices:raise ValueError('no combo rounds')
            parameters={'product_index':product_index,'budget_cents':6000,'choices':choices}
            ways=await agent.scenarios['mcd'].dispatch(session,owner,'mcd_prepare_order',parameters,[])
            way=next(w['index'] for w in ways['take_ways'] if '外带' in str(w) or '自提' in str(w))
            result=await agent.scenarios['mcd'].dispatch(session,owner,'mcd_prepare_order',{**parameters,'take_way_index':way},[])
            plan=result['plan'];assert not plan.get('order') and plan['amount_cents']<=6000
            await client.post('/api/actions/'+plan['id']+'/cancel-plan',json={})
            override=await send('今天先不吃鱼了。长期喜好不用改，请按本次要求看看鸡肉餐品，预算60元，不要下单。')
            if not any(word in override.get('speech_text','') for word in ('鸡','不吃鱼','不选鱼')):
                raise ValueError('current request lost in speech')
            report['current_request_override_checked']=True
            report.update(passed=True,combo_round_count=len(choices),card_prompt_replayed=True,confirmation_prepared_without_order=True)
    except Exception as exc:
        report['failure_type']=type(exc).__name__
    path=root/'report.json';path.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n');path.chmod(0o600)
    print(json.dumps({k:v for k,v in report.items() if k!='turns'},ensure_ascii=False));print(str(path))
    return 0 if report['passed'] else 1


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--live',action='store_true')
    if not parser.parse_args().live:parser.error('--live required')
    raise SystemExit(asyncio.run(run()))
